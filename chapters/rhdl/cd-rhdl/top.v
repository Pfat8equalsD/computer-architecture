module top_regs_rg_0(input wire [1:0] clock_reset, input wire [15:0] i, output reg [15:0] o);
   wire  clock;
   wire  reset;
   assign clock = clock_reset[0];
   assign reset = clock_reset[1];
   initial begin
      o = 16'b0000000000000000;
   end
   always @(posedge clock) begin
      if (reset) begin
         o <= 16'b0000000000000000;
      end else begin
         o <= i;
      end
   end
endmodule
